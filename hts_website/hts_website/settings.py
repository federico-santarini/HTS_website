# Media files (user uploads)
# Immagini caricate dall'admin (progetti, contributor, referenze). In sviluppo le serve
# Django (vedi hts_website/urls.py, solo con DEBUG). In produzione su Railway il filesystem
# si azzera a ogni deploy: servirà uno storage esterno (es. Cloudflare R2). Vedi README.

MEDIA_URL = "media/"
